import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const liveRoot = resolve(here, "..");
const repoRoot = resolve(liveRoot, "..", "..");

const sources = [
  "packages/primitives/src/styles.css",
  "packages/components/src/styles.css",
  "packages/sections/src/styles.css",
  "packages/sections/src/shell-styles.css",
  "packages/sections/src/content-sections.css",
  "packages/sections/src/conversion-styles.css",
  "packages/sections/src/media-sections.css",
  "packages/sections/src/palette-runtime.css",
  "packages/sections/src/image-slots.css",
];

const chunks = [];
for (const source of sources) {
  const absolute = resolve(repoRoot, source);
  const css = await readFile(absolute, "utf8");
  chunks.push(`/* ${source} */\n${css.trim()}\n`);
}

const css = `/* Generated by apps/live/scripts/build-runtime-css.mjs. Do not edit directly. */\n${chunks.join("\n")}`;
const output = resolve(liveRoot, "generated", "runtime-css.ts");
await mkdir(dirname(output), { recursive: true });
await writeFile(output, `export const MICIRQL_RUNTIME_CSS = ${JSON.stringify(css)};\n`, "utf8");
console.log(`Generated ${output} from ${sources.length} shared stylesheets.`);
