import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const liveRoot = resolve(here, "..");
const repoRoot = resolve(liveRoot, "..", "..");

const coreSources = [
  "packages/primitives/src/styles.css",
  "packages/components/src/styles.css",
  "packages/sections/src/styles.css",
  "packages/sections/src/shell-styles.css",
  "packages/sections/src/content-sections.css",
  "packages/sections/src/conversion-styles.css",
  "packages/sections/src/media-sections.css",
  "packages/sections/src/palette-runtime.css",
  "packages/sections/src/image-slots.css",
  "packages/sections/src/premium-mobile.css",
  "packages/sections/src/dental-layout-blueprints.css",
];

const sectionSourceDirectory = resolve(repoRoot, "packages", "sections", "src");
const curatedDentalFiles = (await readdir(sectionSourceDirectory))
  .filter((name) => /^dental-\d{2}-.*\.css$/.test(name));

const byLayoutThenName = (a, b) => {
  const layoutA = a.match(/^dental-(\d{2})-/)?.[1] ?? "99";
  const layoutB = b.match(/^dental-(\d{2})-/)?.[1] ?? "99";
  return layoutA === layoutB ? a.localeCompare(b) : layoutA.localeCompare(layoutB);
};

// Mirror apps/builder/app/layout.tsx exactly at the cascade level:
// 1) base curated layouts
// 2) shared responsive/premium safety layers
// 3) layout-specific refinements
// This ensures the published runtime renders the same premium result as preview.
const curatedDentalBaseSources = curatedDentalFiles
  .filter((name) => !/-refinement\.css$/.test(name))
  .sort(byLayoutThenName)
  .map((name) => `packages/sections/src/${name}`);

const curatedDentalRefinementSources = curatedDentalFiles
  .filter((name) => /-refinement\.css$/.test(name))
  .sort(byLayoutThenName)
  .map((name) => `packages/sections/src/${name}`);

const dentalSafetySource = "packages/sections/src/dental-responsive-safety.css";
const premiumOutputSource = "packages/sections/src/premium-output-system.css";
const premiumGeometrySource = "packages/sections/src/premium-geometry.css";

const sources = [
  ...coreSources,
  ...curatedDentalBaseSources,
  dentalSafetySource,
  premiumOutputSource,
  premiumGeometrySource,
  ...curatedDentalRefinementSources,
];

const chunks = [];
for (const source of sources) {
  const absolute = resolve(repoRoot, source);
  const css = await readFile(absolute, "utf8");
  chunks.push(`/* ${source} */\n${css.trim()}\n`);
}

const css = `/* Generated by apps/live/scripts/build-runtime-css.mjs. Do not edit directly. */\n${chunks.join("\n")}`;
const output = resolve(liveRoot, "generated", "runtime-css.ts");
await mkdir(dirname(output), { recursive: true });
await writeFile(output, `export const MICIRQL_RUNTIME_CSS = ${JSON.stringify(css)};\n`, "utf8");
console.log(`Generated ${output} from ${sources.length} shared stylesheets (${curatedDentalBaseSources.length} Dental base layouts + ${curatedDentalRefinementSources.length} refinement layers + shared safety/premium layers).`);
